  echo "── hook fixtures ──"
  if out=$(bash "$CLAUDE_HOME/hooks/tests/test-hooks.sh" 2>&1); then ok "$(echo "$out" | tail -1 | tr -s ' ')"
  else note "hook fixtures FAILED: $(echo "$out" | grep '❌' | head -3 | tr '\n' ' ')"; fi
