echo "── helper references ──"
missing=$(grep -rhoE "~/\.claude/scripts/[A-Za-z0-9_.-]+" "$CLAUDE_HOME/skills" "$RULEBOOK" 2>/dev/null | sort -u | while read -r r; do
  p="${r/#\~/$HOME}"; [ -e "$p" ] || echo "$r"; done)
if [ -n "$missing" ]; then cannot "skills name helpers that do not exist: $(echo $missing)"; else ok "every ~/.claude/scripts/* reference resolves"; fi

badcase=$(grep -rlE "\.Codex/" "$CLAUDE_HOME/skills" "$AGENTS_DIR/skills" 2>/dev/null | sort -u)
if [ -n "$badcase" ]; then cannot "importer-rewritten .Codex/ paths present in: $(echo $badcase)"; else ok "no rewritten .Codex/ paths"; fi

