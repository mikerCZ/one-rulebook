mkdir -p "$(dirname "$REPORT")"
# Order: <report> <mode> <repaired count> <failed count> <repaired…> -- <failed…> -- <drift…>
if ! CODEX_HOME="$CODEX_HOME" python3 - "$REPORT" "$MODE" "${#repaired[@]}" "${#failed[@]}" \
     "${repaired[@]:-}" "--" "${failed[@]:-}" "--" "${advisory[@]:-}" "--" "${drift[@]:-}" <<'PY'
import json, os, sys, time
report, mode = sys.argv[1], sys.argv[2]
nr, nf = int(sys.argv[3]), int(sys.argv[4])
rest = sys.argv[5:]
def take(seq):
    out = []
    while seq and seq[0] != "--":
        if seq[0]:
            out.append(seq[0])
        seq.pop(0)
    if seq:
        seq.pop(0)
    return out
repaired = take(rest); failed = take(rest); advisory = take(rest)
items = [d for d in rest if d]

# When the native importer last ran. Recording it next to the drift makes the two attributable:
# drift that appears with a NEW timestamp is the importer taking a target back, drift with the
# same timestamp is something else (a hand edit, a moved file).
last_import = None
try:
    g = json.load(open(os.path.join(os.environ.get("CODEX_HOME", os.path.expanduser("~/.codex")), ".codex-global-state.json")))
    st = g.get("electron-persisted-atom-state", {}).get("external-agent-import-sync-state", {})
    ms = st.get("lastSyncStartedAtMs")
    if ms:
        last_import = time.strftime("%Y-%m-%dT%H:%M:%S%z", time.localtime(ms / 1000))
except Exception:
    pass

json.dump({"checked_at": time.strftime("%Y-%m-%dT%H:%M:%S%z"), "mode": mode,
           "native_import_last_run": last_import,
           "drift_count": len(items), "drift": items,
           "repaired_count": nr, "repaired": repaired,
           "unrepaired_count": nf, "unrepaired": failed,
           "needs_a_human_count": len(advisory), "needs_a_human": advisory},
          open(report, "w"), indent=1, ensure_ascii=False)
PY
then
  # A report that cannot be written is the instrument going dark, and the previous file would sit
  # there looking current. Say so instead.
  cannot "the JSON report at $REPORT could not be written"
fi

echo
NF=${#failed[@]}; NR=${#repaired[@]}; ND=${#drift[@]}

# Structural guard, not a per-call-site promise: a finding that was reported and NOT repaired keeps
# --apply from returning green, whoever adds the next check and whatever bucket they choose. The
# version before this one relied on each site picking the right one, and a permission change that
# called note() alone came out as "in sync" (reproduced 5.9.2026).
REMAINING=$(( ND - NR ))
[ "$REMAINING" -lt 0 ] && REMAINING=0

if [ "$MODE" = "--apply" ]; then
  # A repair that was made and a repair that could not be made are different outcomes and get
  # different exit codes. Saying "repaired" for both is what let a refused write report success.
  if [ "$NF" -gt 0 ] || [ "$REMAINING" -gt 0 ]; then
    notify "codex-sync: needs a human" "$NF item(s) could NOT be repaired — see codex-sync-report.json"
    echo "repaired $NR item(s); $NF unrepairable, $REMAINING left unhandled — report in $REPORT" >&2
    exit 1
  fi
  if [ "$NR" -gt 0 ]; then
    # Drift that was repaired is still a signal: these targets have one other plausible writer,
    # and repairing in silence would hide the day the importer starts taking them back.
    notify "codex-sync: Codex config had drifted" "$NR item(s) repaired — see codex-sync-report.json"
    echo "repaired $NR item(s) — report in $REPORT"
    exit 0
  fi
  if [ "${#advisory[@]}" -gt 0 ]; then
    # Nothing to repair and nothing to notify: these need a person, and saying "in sync" over
    # them would be the false green this whole script exists to prevent.
    echo "nothing to repair here; ${#advisory[@]} item(s) need a human — report in $REPORT"
    exit 0
  fi
  echo "in sync — report in $REPORT"; exit 0
fi

if [ "$NF" -gt 0 ] || [ "$ND" -gt 0 ] || [ "${#advisory[@]}" -gt 0 ]; then
  echo "drift: $ND item(s), $NF unrepairable, ${#advisory[@]} need a human — report in $REPORT"; exit 1
fi
echo "in sync — report in $REPORT"
